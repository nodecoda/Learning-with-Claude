"""C99 backend: lower the mini IR into a standalone DLL."""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from .ir import Graph, IRError, Op, TensorType, Value, broadcast_strides
from .memory import MemoryPlan, plan_memory


def _ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def _c_float(x: float) -> str:
    value = float(x)
    if value == 0.0:
        return "0.0f"
    text = f"{value:.9g}"
    if "e" not in text and "E" not in text and "." not in text:
        text += ".0"
    return text + "f"


def _array_literal(data: np.ndarray, *, per_line: int = 8) -> str:
    flat = np.asarray(data, dtype=np.float32).reshape(-1)
    if flat.size == 0:
        flat = np.zeros(1, dtype=np.float32)
    parts = [_c_float(v) for v in flat]
    lines = []
    for i in range(0, len(parts), per_line):
        lines.append("    " + ", ".join(parts[i : i + per_line]) + ("," if i + per_line < len(parts) else ""))
    return "\n".join(lines)


def _linear_index(shape: tuple[int, ...], strides: tuple[int, ...], vars_: list[str]) -> str:
    terms: list[str] = []
    for d, s, var in zip(shape, strides, vars_):
        if s == 0:
            continue
        if s == 1:
            terms.append(var)
        else:
            terms.append(f"({var})*{s}")
    return " + ".join(terms) if terms else "0"


def _broadcast_index(shape: tuple[int, ...], out_shape: tuple[int, ...], vars_: list[str]) -> str:
    return _linear_index(out_shape, broadcast_strides(shape, out_shape), vars_)


class CCodegen:
    def __init__(self, graph: Graph, plan: MemoryPlan | None = None, *, function_name: str = "mini_forward") -> None:
        self.graph = graph
        self.plan = plan or plan_memory(graph)
        self.function_name = function_name
        self.input_index = {id(v): i for i, v in enumerate(graph.inputs)}
        self.output_index = {id(v): i for i, v in enumerate(graph.outputs)}
        self.value_name = {id(v): f"v_{v.id}_{_ident(v.name)}" for v in graph.values}
        self.const_name = {id(v): f"C_{v.id}" for v in graph.values if v.kind == "constant"}

    def ptr(self, v: Value) -> str:
        return self.value_name[id(v)]

    def _expr_input_index(self, v: Value, out_shape: tuple[int, ...], vars_: list[str]) -> str:
        return _broadcast_index(v.type.shape, out_shape, vars_)

    def emit(self) -> str:
        self.graph.validate()
        lines: list[str] = []
        lines.append("/* Generated by mini_ai.codegen_c. */")
        lines.append("#include <stddef.h>")
        lines.append("#include <math.h>")
        lines.append("#if defined(_MSC_VER)")
        lines.append("#include <malloc.h>")
        lines.append("#endif")
        lines.append("")
        lines.append("#if defined(_MSC_VER)")
        lines.append("#define MINI_EXPORT __declspec(dllexport)")
        lines.append("#else")
        lines.append("#define MINI_EXPORT")
        lines.append("#endif")
        lines.append("")
        for v in self.graph.values:
            if v.kind == "constant":
                assert v.data is not None
                n = max(1, v.type.numel)
                lines.append(f"static const float {self.const_name[id(v)]}[{n}] = {{")
                lines.append(_array_literal(v.data))
                lines.append("};")
        lines.append("")
        sig_inputs = [f"const float* x{i}" for i in range(len(self.graph.inputs))]
        sig_outputs = [f"float* out{i}" for i in range(len(self.graph.outputs))]
        lines.append(f"MINI_EXPORT int {self.function_name}({', '.join(sig_inputs + sig_outputs)}) {{")
        arena = max(64, self.plan.arena_bytes)
        lines.append(f"    const size_t arena_bytes = {arena};")
        lines.append("#if defined(_MSC_VER)")
        lines.append("    float* arena = (float*)_aligned_malloc(arena_bytes, 64);")
        lines.append("#else")
        lines.append("    float* arena = (float*)aligned_alloc(64, arena_bytes);")
        lines.append("#endif")
        lines.append("    if (!arena) return 1;")
        lines.append("")
        for v in self.graph.values:
            if v.kind == "input":
                lines.append(f"    const float* {self.ptr(v)} = x{self.input_index[id(v)]};")
            elif v.kind == "constant":
                lines.append(f"    const float* {self.ptr(v)} = {self.const_name[id(v)]};")
            elif id(v) in {id(a.value) for a in self.plan.allocations.values()}:
                off = self.plan.offset_of(v)
                lines.append(f"    float* {self.ptr(v)} = (float*)((char*)arena + {off});")
        lines.append("")
        for op in self.graph.ops:
            lines.append(f"    /* {op.kind}: {op.output.name} */")
            self._emit_op(op, lines)
            lines.append("")
        for i, v in enumerate(self.graph.outputs):
            n = max(1, v.type.numel)
            lines.append(f"    for (int i = 0; i < {n}; ++i) out{i}[i] = {self.ptr(v)}[i];")
        lines.append("")
        lines.append("#if defined(_MSC_VER)")
        lines.append("    _aligned_free(arena);")
        lines.append("#else")
        lines.append("    free(arena);")
        lines.append("#endif")
        lines.append("    return 0;")
        lines.append("}")
        return "\n".join(lines) + "\n"

    def _emit_op(self, op: Op, lines: list[str]) -> None:
        kind = op.kind
        out = op.output
        out_shape = out.type.shape
        if kind in {"add", "sub", "mul", "div", "relu", "exp", "add_relu"}:
            self._emit_elementwise(op, lines)
            return
        if kind in {"matmul", "matmul_bias", "matmul_bias_relu"}:
            self._emit_matmul(op, lines)
            return
        if kind == "sum":
            self._emit_sum(op, lines)
            return
        if kind == "softmax":
            raise IRError("C backend does not implement softmax yet; use sum/exp/div")
        raise IRError(f"C backend does not support op: {kind}")

    def _emit_elementwise(self, op: Op, lines: list[str]) -> None:
        out_shape = op.output.type.shape
        rank = len(out_shape)
        vars_ = [f"i{op.id}_{d}" for d in range(rank)]
        indent = "    "
        if rank == 0:
            self._emit_expr(op, lines, indent, [], "0")
            return
        for d, n in enumerate(out_shape):
            lines.append(f"{indent}for (int {vars_[d]} = 0; {vars_[d]} < {n}; ++{vars_[d]}) {{")
            indent += "    "
        out_idx = _linear_index(out_shape, TensorType(out_shape).strides, vars_)
        self._emit_expr(op, lines, indent, vars_, out_idx)
        for _ in out_shape:
            indent = indent[:-4]
            lines.append(f"{indent}}}")

    def _emit_expr(self, op: Op, lines: list[str], indent: str, vars_: list[str], out_idx: str) -> None:
        dst = self.ptr(op.output)
        ins = [self.ptr(v) for v in op.inputs]
        idx = [self._expr_input_index(v, op.output.type.shape, vars_) for v in op.inputs]
        k = op.kind
        if k == "relu":
            expr = f"fmaxf({ins[0]}[{idx[0]}], 0.0f)"
        elif k == "exp":
            expr = f"expf({ins[0]}[{idx[0]}])"
        elif k == "add":
            expr = f"{ins[0]}[{idx[0]}] + {ins[1]}[{idx[1]}]"
        elif k == "sub":
            expr = f"{ins[0]}[{idx[0]}] - {ins[1]}[{idx[1]}]"
        elif k == "mul":
            expr = f"{ins[0]}[{idx[0]}] * {ins[1]}[{idx[1]}]"
        elif k == "div":
            expr = f"{ins[0]}[{idx[0]}] / {ins[1]}[{idx[1]}]"
        elif k == "add_relu":
            expr = f"fmaxf({ins[0]}[{idx[0]}] + {ins[1]}[{idx[1]}], 0.0f)"
        else:
            raise IRError(f"not an elementwise op: {k}")
        lines.append(f"{indent}{dst}[{out_idx}] = {expr};")

    def _emit_matmul(self, op: Op, lines: list[str]) -> None:
        a, b = op.inputs[0], op.inputs[1]
        m, k = a.type.shape
        k2, n = b.type.shape
        if k != k2:
            raise IRError(f"matmul shape mismatch: {a.type.shape} @ {b.type.shape}")
        out = op.output
        bias = op.inputs[2] if len(op.inputs) == 3 else None
        i, j, kk = f"i{op.id}", f"j{op.id}", f"k{op.id}"
        lines.append(f"    for (int {i} = 0; {i} < {m}; ++{i}) {{")
        lines.append(f"        for (int {j} = 0; {j} < {n}; ++{j}) {{")
        lines.append("            float acc = 0.0f;")
        lines.append(f"            for (int {kk} = 0; {kk} < {k}; ++{kk}) {{")
        lines.append(
            f"                acc += {self.ptr(a)}[({i})*{k} + ({kk})] * "
            f"{self.ptr(b)}[({kk})*{n} + ({j})];"
        )
        lines.append("            }")
        if bias is not None:
            bias_idx = _broadcast_index(bias.type.shape, (m, n), [i, j])
            lines.append(f"            acc += {self.ptr(bias)}[{bias_idx}];")
        if op.kind == "matmul_bias_relu":
            lines.append("            acc = fmaxf(acc, 0.0f);")
        lines.append(f"            {self.ptr(out)}[({i})*{n} + ({j})] = acc;")
        lines.append("        }")
        lines.append("    }")

    def _emit_sum(self, op: Op, lines: list[str]) -> None:
        x = op.inputs[0]
        out = op.output
        axis = op.attrs.get("axis", None)
        keepdims = bool(op.attrs.get("keepdims", False))
        shape = x.type.shape
        rank = len(shape)
        vars_ = [f"i{op.id}_{d}" for d in range(rank)]
        lines.append(f"    for (int z = 0; z < {max(1, out.type.numel)}; ++z) {self.ptr(out)}[z] = 0.0f;")
        if axis is None:
            lines.append(f"    for (int z = 0; z < {max(1, x.type.numel)}; ++z) {self.ptr(out)}[0] += {self.ptr(x)}[z];")
            return
        if axis < 0:
            axis += rank
        indent = "    "
        for d, dim in enumerate(shape):
            lines.append(f"{indent}for (int {vars_[d]} = 0; {vars_[d]} < {dim}; ++{vars_[d]}) {{")
            indent += "    "
        in_idx = _linear_index(shape, TensorType(shape).strides, vars_)
        if keepdims:
            out_vars = [v if d != axis else "0" for d, v in enumerate(vars_)]
            out_shape = out.type.shape
        else:
            out_vars = [v for d, v in enumerate(vars_) if d != axis]
            out_shape = out.type.shape
        out_idx = _linear_index(out_shape, TensorType(out_shape).strides, out_vars)
        lines.append(f"{indent}{self.ptr(out)}[{out_idx}] += {self.ptr(x)}[{in_idx}];")
        for _ in shape:
            indent = indent[:-4]
            lines.append(f"{indent}}}")


def generate_c(graph: Graph, plan: MemoryPlan | None = None, *, function_name: str = "mini_forward") -> str:
    return CCodegen(graph, plan, function_name=function_name).emit()


@dataclass
class CCompileResult:
    code_path: Path
    dll_path: Path
    build_log: str


def find_vcvars64() -> Path:
    candidates = [
        os.environ.get("VCVARS64", ""),
        r"D:\VStudio\2022\Enterprise\VC\Auxiliary\Build\vcvars64.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Enterprise\VC\Auxiliary\Build\vcvars64.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvars64.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars64.bat",
        r"C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat",
    ]
    for item in candidates:
        if item and Path(item).exists():
            return Path(item)
    raise RuntimeError("vcvars64.bat not found; set the VCVARS64 environment variable")


def compile_c(code: str, build_dir: str | Path, *, name: str = "kernel") -> CCompileResult:
    build = Path(build_dir)
    build.mkdir(parents=True, exist_ok=True)
    code_path = build / f"{name}.c"
    dll_path = build / f"{name}.dll"
    code_path.write_text(code, encoding="utf-8")
    vcvars = find_vcvars64()
    bat = build / "build.bat"
    bat.write_text(
        "@echo off\n"
        f'call "{vcvars}" >nul\n'
        "if errorlevel 1 exit /b 2\n"
        f'cl /nologo /LD /O2 /fp:fast /Fe:{name}.dll {name}.c > build.log 2>&1\n'
        "exit /b %errorlevel%\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        ["cmd", "/c", "build.bat"],
        cwd=build,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    log = ""
    log_path = build / "build.log"
    if log_path.exists():
        log = log_path.read_text(encoding="utf-8", errors="replace")
    if proc.returncode != 0 or not dll_path.exists():
        raise RuntimeError(f"cl failed ({proc.returncode})\n{log}\n{proc.stdout}\n{proc.stderr}")
    return CCompileResult(code_path=code_path, dll_path=dll_path, build_log=log)


def compile_graph_c(graph: Graph, build_dir: str | Path, *, name: str = "kernel") -> CCompileResult:
    return compile_c(generate_c(graph), build_dir, name=name)
